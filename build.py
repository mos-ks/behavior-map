# ----------------------------------------------------------------------------- parsing

def parse_scalar(raw):
    v = raw.strip()
    if v.startswith('"'):
        try:
            value, _ = json.JSONDecoder().raw_decode(v)
            return value
        except ValueError:
            raise BuildError("bad quoted value: " + raw)
    v = re.sub(r"\s+#.*$", "", v).strip()
    if v.startswith("[") and v.endswith("]"):
        inner = v[1:-1].strip()
        return [parse_scalar(x) for x in inner.split(",")] if inner else []
    if len(v) >= 2 and v[0] == "'" and v[-1] == "'":
        return v[1:-1]
    if v in ("true", "false"):
        return v == "true"
    if v in ("null", "~", ""):
        return None
    if re.fullmatch(r"-?\d+", v):
        return int(v)
    return v


def parse_simple_yaml(text):
    """The small YAML subset the map uses: `key: value`, `[a, b]` lists and `- item` block lists."""
    data, key = {}, None
    for line in text.split("\n"):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        m = re.match(r"^\s+-\s+(.*)$", line) or re.match(r"^-\s+(.*)$", line)
        if m and key is not None and isinstance(data.get(key), list):
            data[key].append(parse_scalar(m.group(1)))
            continue
        m = re.match(r"^([A-Za-z_][\w-]*):(.*)$", line)
        if not m:
            raise BuildError("cannot read line: " + line)
        key, raw = m.group(1), m.group(2)
        if raw.strip() == "":
            data[key] = []
        else:
            data[key] = parse_scalar(raw)
    return data


def parse_rule(text, path=""):
    text = text.replace("\r\n", "\n")
    m = re.match(r"^---\n(.*?)\n---\n?(.*)$", text, re.S)
    if not m:
        raise BuildError("%s: no frontmatter block" % path)
    rule = parse_simple_yaml(m.group(1))
    rule.update(rule="", why=None, boundary=None, earlier=None, example=None, quotes=[], path=path)
    names = {label: key for key, label in FIELD_LABELS}
    field, mode = None, None
    for line in m.group(2).split("\n"):
        s = line.strip()
        fm = FIELD_RE.match(s)
        if fm:
            field, mode = names[fm.group(1)], None
            rule[field] = fm.group(2).strip()
        elif s == QUOTES_HEADING:
            field, mode = None, "quotes"
        elif s == EXAMPLE_HEADING:
            field, mode = None, "example"
            rule["example"] = {"before": "", "after": ""}
        elif not s:
            field = None
        elif mode == "quotes" and s.startswith("- "):
            qm = QUOTE_RE.match(s)
            if not qm:
                raise BuildError('%s: quote line must look like `- 2026-01-31, project: "words"`: %s' % (path, s))
            date = qm.group(1).strip()
            rule["quotes"].append({"date": None if date == "undated" else date,
                                   "project": qm.group(2).strip(), "quote": qm.group(3)})
        elif mode == "example" and s.startswith("- Before:"):
            rule["example"]["before"] = s[len("- Before:"):].strip()
        elif mode == "example" and s.startswith("- After:"):
            rule["example"]["after"] = s[len("- After:"):].strip()
        elif field:
            rule[field] = (rule[field] + " " + s).strip()
    return rule


def render_rule(rule):
    """Rule dict back to file text (used by the merge, the tests and the editing page)."""
    def fmt(key, v):
        if isinstance(v, bool):
            return "true" if v else "false"
        if v is None:
            return "null"
        if isinstance(v, list):
            return "[" + ", ".join(str(x) for x in v) + "]"
        if key in ("title", "short", "chat_about"):
            return json.dumps(v, ensure_ascii=False)
        return str(v)
    out = ["---"]
    for key in FRONTMATTER_ORDER:
        if key in REQUIRED or rule.get(key) not in (None, ""):
            out.append("%s: %s" % (key, fmt(key, rule.get(key))))
    out.append("---")
    for key, label in FIELD_LABELS:
        if rule.get(key):
            out += ["", "**%s.** %s" % (label, rule[key])]
    if rule.get("example"):
        out += ["", EXAMPLE_HEADING, "- Before: " + rule["example"]["before"], "- After: " + rule["example"]["after"]]
    if rule.get("quotes"):
        out += ["", QUOTES_HEADING]
        out += ['- %s, %s: "%s"' % (q["date"] or "undated", q["project"], q["quote"]) for q in rule["quotes"]]
    return "\n".join(out) + "\n"


def read_text(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def write_text(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def full_path(root, rel):
    return os.path.join(root, *rel.split("/"))


def folder_text(root):
    return os.path.abspath(root).replace(os.sep, "/")


def parse_day(value):
    """A date from `2026-11-10` or a longer timestamp; None when there is none."""
    try:
        return datetime.date.fromisoformat(str(value)[:10])
    except ValueError:
        return None


def render_profile(p):
    """Profile dict back to file text (the editing page changes the core list)."""
    out = ["name: " + p["name"], "description: " + str(p["description"]), "include_scopes: [%s]" % ", ".join(p["include_scopes"])]
    out.append("include_ids:" if p["include_ids"] else "include_ids: []")
    out += ["  - " + i for i in p["include_ids"]]
    out.append("exclude_ids: [%s]" % ", ".join(p["exclude_ids"]))
    return "\n".join(out) + "\n"


def rule_sort_key(r):
    cat = r.get("category")
    return (CATEGORIES.index(cat) if cat in CATEGORIES else 99, -int(r.get("times_seen") or 0), str(r.get("id")))


def load_rules(root=ROOT):
    """Returns (rules, errors). A file that does not parse becomes an error, not a crash."""
    rules, errors = [], []
    base = os.path.join(root, "rules")
    for folder, _dirs, files in os.walk(base):
        for name in sorted(files):
            if not name.endswith(".md"):
                continue
            full = os.path.join(folder, name)
            rel = os.path.relpath(full, root).replace(os.sep, "/")
            try:
                rules.append(parse_rule(read_text(full), rel))
            except BuildError as e:
                errors.append(str(e) if rel in str(e) else "%s: %s" % (rel, e))
    rules.sort(key=rule_sort_key)
    return rules, errors


def load_profiles(root=ROOT):
    profiles, errors = [], []
    base = os.path.join(root, "profiles")
    if os.path.isdir(base):
        for name in sorted(os.listdir(base)):
            if not name.endswith((".yaml", ".yml")):
                continue
            try:
                p = parse_simple_yaml(read_text(os.path.join(base, name)))
            except BuildError as e:
                errors.append("profiles/%s: %s" % (name, e))
                continue
            p.setdefault("name", os.path.splitext(name)[0])
            for key in ("include_scopes", "include_ids", "exclude_ids"):
                p[key] = p.get(key) or []
            p.setdefault("description", "")
            profiles.append(p)
    profiles.sort(key=lambda p: (p["name"] != "core", p["name"]))
    return profiles, errors


def select(profile, rules):
    """The enabled rules a profile picks. Scopes first (by category), then extra ids in the order listed."""
    by_id = {r["id"]: r for r in rules}
    missing = [i for i in profile["include_ids"] + profile["exclude_ids"] if i not in by_id]
    if missing:
        raise BuildError("profile %s names rules that do not exist: %s" % (profile["name"], ", ".join(missing)))
    excluded = set(profile["exclude_ids"])
    picked, seen = [], set()
    by_scope = sorted((r for r in rules if r.get("scope") in profile["include_scopes"]), key=rule_sort_key)
    for r in by_scope + [by_id[i] for i in profile["include_ids"]]:
        if r["id"] in seen or r["id"] in excluded or r.get("enabled") is not True:
            continue
        seen.add(r["id"])
        picked.append(r)
    if profile["include_scopes"]:
        picked.sort(key=rule_sort_key)
    return picked


# ----------------------------------------------------------------------------- validation

def has_dash(text):
    return any(d in text for d in DASHES) or " -- " in text


def validate(rules, profiles, root=ROOT):
    errors, ids = [], {}
    for r in rules:
        where = r.get("path") or str(r.get("id"))
        for key in REQUIRED:
            if key not in r:
                errors.append("%s: missing field `%s`" % (where, key))
        if not r.get("rule"):
            errors.append("%s: no **Rule.** text" % where)
        rid = str(r.get("id") or "")
        if rid in ids:
            errors.append("%s: id `%s` is already used by %s" % (where, rid, ids[rid]))
        ids[rid] = where
        cat, scope = r.get("category"), str(r.get("scope") or "")
        if cat not in CATEGORIES:
            errors.append("%s: unknown category `%s`" % (where, cat))
        elif not rid.startswith(cat + "-"):
            errors.append("%s: id must start with its category (`%s-`)" % (where, cat))
        elif r.get("path") and rid != "%s-%s" % (cat, os.path.basename(r["path"])[:-len(".md")]):
            errors.append("%s: id must be the category, a dash and the file name (`%s-%s`)" % (where, cat, os.path.basename(r["path"])[:-len(".md")]))
        is_project = scope.startswith("project:") and len(scope) > len("project:")
        if scope not in SCOPES and not is_project:
            errors.append("%s: unknown scope `%s`" % (where, scope))
        if r.get("path"):
            in_project_folder = r["path"].startswith("rules/_project/")
            if is_project != in_project_folder:
                errors.append("%s: project-only rules (scope project:<name>) live under rules/_project/<name>/, all others outside it" % where)
        if r.get("strength") not in STRENGTHS:
            errors.append("%s: strength must be hard or soft" % where)
        for key in ("enabled", "needs_owner"):
            if key in r and not isinstance(r[key], bool):
                errors.append("%s: `%s` must be true or false" % (where, key))
        if "times_seen" in r and not isinstance(r["times_seen"], int):
            errors.append("%s: `times_seen` must be a number" % where)
        if "sources" in r and not isinstance(r["sources"], list):
            errors.append("%s: `sources` must be a list like [A, B]" % where)
        for key in ("rule", "short", "boundary"):
            if has_dash(str(r.get(key) or "")):
                errors.append("%s: em dash or dash break in the %s text" % (where, key))
        if r.get("short") and len(str(r["short"]).split()) > MAX_SHORT_WORDS:
            errors.append("%s: `short` has more than %d words" % (where, MAX_SHORT_WORDS))
        if r.get("chat") not in (None, "respond"):
            errors.append("%s: `chat` can only be `respond`" % where)

    names = [p["name"] for p in profiles]
    if "core" not in names:
        errors.append("profiles/core.yaml is missing")
    for p in profiles:
        for s in p["include_scopes"]:
            if s not in SCOPES:
                errors.append("profile %s: unknown scope `%s`" % (p["name"], s))
        try:
            picked = select(p, rules)
        except BuildError as e:
            errors.append(str(e))
            continue
        if p["name"] == "core":
            for r in picked:
                if not r.get("short"):
                    errors.append("%s: every core rule needs a `short:` line (at most %d words)" % (r.get("path"), MAX_SHORT_WORDS))

    conflicts = os.path.join(root, "conflicts.md")
    if os.path.isfile(conflicts):
        prefix = "|".join(re.escape(c) for c in CATEGORIES)
        for token in sorted(set(re.findall(r"`((?:%s)-[a-z0-9-]+)`" % prefix, read_text(conflicts)))):
            if token not in ids:
                errors.append("conflicts.md names a rule that does not exist: `%s`" % token)
    return errors


# ----------------------------------------------------------------------------- exports

def bullet(rule):
    return "- " + str(rule.get("short") or rule["rule"])


def core_document(rules, profiles):
    core = next(p for p in profiles if p["name"] == "core")
    picked = select(core, rules)
    lines = ["<!-- %s -->" % GENERATED,
             "# How to work with the owner",
             PLACEHOLDER_LINE,
             "\"The owner\" is the person you work for. These rules hold in every session.",
             PRECEDENCE]
    for heading, cats in CORE_GROUPS:
        group = [r for r in picked if r["category"] in cats]
        if group:
            lines += ["", "## " + heading] + [bullet(r) for r in group]
    left = [r["id"] for r in picked if not any(r["category"] in cats for _h, cats in CORE_GROUPS)]
    if left:
        raise BuildError("core rules without a heading in CORE_GROUPS: " + ", ".join(left))
    others = [p for p in profiles if p["name"] != "core"]
    if others:
        lines += ["", "## More, by task", "Before work of one of these kinds, read its file:"]
        for p in others:
            lines.append("- `<BEHAVIOR_MAP_DIR>/exports/profile-%s.md`: %s." % (p["name"], str(p["description"]).rstrip(".")))
    return "\n".join(lines) + "\n"


def profile_document(profile, rules):
    picked = select(profile, rules)
    lines = ["<!-- %s -->" % GENERATED,
             "# Profile: " + profile["name"],
             str(profile["description"]).rstrip(".") + ". Rules marked (soft) are defaults, the others are firm."]
    for cat in CATEGORIES:
        group = [r for r in picked if r["category"] == cat]
        if not group:
            continue
        lines += ["", "## " + cat]
        for r in group:
            lines.append("- " + r["rule"] + (" (soft)" if r["strength"] == "soft" else ""))
            if r.get("boundary"):
                lines.append("  Applies: " + r["boundary"])
    return "\n".join(lines) + "\n"


def project_names(rules):
    return sorted({str(r["scope"])[len("project:"):] for r in rules if str(r["scope"]).startswith("project:") and r.get("enabled") is True})


def project_document(name, rules):
    """The rules that hold in one project only. Nothing reads it until that project's own instruction file names it."""
    lines = ["<!-- %s -->" % GENERATED, "# Rules for %s only" % name,
             "These hold in this project on top of the general rules. Rules marked (soft) are defaults, the others are firm."]
    for r in sorted((r for r in rules if r["scope"] == "project:" + name and r.get("enabled") is True), key=rule_sort_key):
        lines.append("- " + r["rule"] + (" (soft)" if r["strength"] == "soft" else ""))
        if r.get("boundary"):
            lines.append("  Applies: " + r["boundary"])
    return "\n".join(lines) + "\n"


def chat_blocks(rules, profiles):
    core = next(p for p in profiles if p["name"] == "core")
    core_rules = select(core, rules)
    core_ids = {r["id"] for r in core_rules}
    ordered = core_rules + [r for r in rules if r["id"] not in core_ids and r.get("enabled") is True]
    about = "\n".join(str(r["chat_about"]) for r in ordered if r.get("chat_about"))
    respond = "\n".join(bullet(r) for r in ordered if r.get("chat") == "respond")
    return about, respond


def chatgpt_document(rules, profiles):
    about, respond = chat_blocks(rules, profiles)
    parts = ["# " + GENERATED,
             "# Paste each block into the ChatGPT field of the same name. Each block may hold at most %d characters." % MAX_CHAT_BLOCK]
    for title, block in ((CHAT_ABOUT_TITLE, about), (CHAT_RESPOND_TITLE, respond)):
        if len(block) > MAX_CHAT_BLOCK:
            raise BuildError("ChatGPT block '%s' has %d characters, the limit is %d. Remove `chat` fields or shorten `short` lines."
                             % (title, len(block), MAX_CHAT_BLOCK))
        parts += ["", "=== %s (%d of %d characters) ===" % (title, len(block), MAX_CHAT_BLOCK), block]
    return "\n".join(parts) + "\n"


def recency_weights(rules):
    """times_seen, halved for every HALF_LIFE_DAYS since the rule was last stated. Ages are measured from the
    newest date in the map, not from today, so the same files always build the same exports."""
    days = {r["id"]: parse_day(r.get("last_seen")) for r in rules}
    newest = max((d for d in days.values() if d), default=None)
    out = {}
    for r in rules:
        age = (newest - days[r["id"]]).days if newest and days[r["id"]] else 2 * HALF_LIFE_DAYS
        out[r["id"]] = int(r["times_seen"]) * 0.5 ** (age / HALF_LIFE_DAYS)
    return out


def local_document(rules, profiles):
    core = next(p for p in profiles if p["name"] == "core")
    picked = select(core, rules)
    head = ["<!-- %s -->" % GENERATED, "You work for one person, the owner. Follow these rules in every reply."]
    budget = MAX_LOCAL_WORDS - sum(len(x.split()) for x in head)
    chosen = set()
    # rules marked `local: true` first, then the most often and most recently stated
    weight = recency_weights(rules)
    for r in sorted(picked, key=lambda r: (r.get("local") is not True, -weight[r["id"]], r["id"])):
        words = len(bullet(r).split())
        if words <= budget:
            chosen.add(r["id"])
            budget -= words
    return "\n".join(head + [bullet(r) for r in picked if r["id"] in chosen]) + "\n"


def yes_no(v):
    return "yes" if v else "no"


def index_document(rules):
    glob = [r for r in rules if not str(r["scope"]).startswith("project:")]
    proj = [r for r in rules if str(r["scope"]).startswith("project:")]
    lines = ["<!-- %s -->" % GENERATED, "# Behaviour map: all rules", "",
             "- Rules: %d (%d global, %d project-only)" % (len(rules), len(glob), len(proj)),
             "- Hard: %d, soft: %d" % (sum(r["strength"] == "hard" for r in rules), sum(r["strength"] == "soft" for r in rules)),
             "- Turned off: %d" % sum(r["enabled"] is not True for r in rules),
             "- Waiting for the owner (see conflicts.md): %d" % sum(bool(r["needs_owner"]) for r in rules),
             "", "| Category | Rules | Hard | Soft |", "|---|---|---|---|"]
    for cat in CATEGORIES:
        g = [r for r in rules if r["category"] == cat]
        lines.append("| %s | %d | %d | %d |" % (cat, len(g), sum(r["strength"] == "hard" for r in g), sum(r["strength"] == "soft" for r in g)))
    head = ["| Title | Scope | Strength | Times seen | Enabled | Needs owner |", "|---|---|---|---|---|---|"]

    def row(r):
        return "| [%s](%s) | %s | %s | %d | %s | %s |" % (str(r["title"]).replace("|", "/"), r["path"].replace(" ", "%20"), r["scope"],
                                                        r["strength"], r["times_seen"], yes_no(r["enabled"] is True), yes_no(r["needs_owner"]))
    for cat in CATEGORIES:
        g = [r for r in glob if r["category"] == cat]
        if g:
            lines += ["", "## " + cat, ""] + head + [row(r) for r in g]
    if proj:
        lines += ["", "## Project-only (not exported to the global files)", ""] + head
        lines += [row(r) for r in sorted(proj, key=lambda r: (r["scope"], rule_sort_key(r)))]
    return "\n".join(lines) + "\n"


def rules_json(rules):
    keys = FRONTMATTER_ORDER + ["rule", "why", "boundary", "earlier", "example", "quotes", "path"]
    data = {"generated": GENERATED, "categories": CATEGORIES, "scopes": SCOPES,
            "rules": [{k: r.get(k) for k in keys} for r in rules]}
    return json.dumps(data, ensure_ascii=False, indent=1) + "\n"


def build_outputs(rules, profiles):
    """Every generated file as {relative path: text}. Raises BuildError when a limit is broken."""
    out = {}
    core = core_document(rules, profiles)
    out["exports/CLAUDE.md"] = core
    out["exports/AGENTS.md"] = core
    for p in profiles:
        if p["name"] != "core":
            out["exports/profile-%s.md" % p["name"]] = profile_document(p, rules)
    out["exports/chatgpt-custom-instructions.txt"] = chatgpt_document(rules, profiles)
    out["exports/system-prompt-local.md"] = local_document(rules, profiles)
    for name in project_names(rules):
        out["exports/project-%s.md" % name] = project_document(name, rules)
    out["index.md"] = index_document(rules)
    out["rules.json"] = rules_json(rules)
    return out


def check_outputs(outputs, rules):
    errors = []
    for name in ("exports/CLAUDE.md", "exports/AGENTS.md"):
        text = outputs[name]
        n = len(text.rstrip("\n").split("\n"))
        if n > MAX_CORE_LINES:
            errors.append("%s has %d lines, the limit is %d. Take a rule out of profiles/core.yaml." % (name, n, MAX_CORE_LINES))
        headings = [l for l in text.split("\n") if l.startswith("## ") and l != "## More, by task"]
        if not 5 <= len(headings) <= 7:
            errors.append("%s has %d core headings, it should have 5 to 7" % (name, len(headings)))
    if re.search(r"claude", outputs["exports/AGENTS.md"], re.I):
        errors.append("exports/AGENTS.md mentions Claude; it must be tool-neutral")
    words = len(outputs["exports/system-prompt-local.md"].split())
    if words > MAX_LOCAL_WORDS:
        errors.append("exports/system-prompt-local.md has %d words, the limit is %d" % (words, MAX_LOCAL_WORDS))
    quotes = [q["quote"] for r in rules for q in r.get("quotes", []) if len(q["quote"]) >= 40]   # shorter ones can match rule wording by chance
    for name, text in outputs.items():
        if not name.startswith("exports/"):
            continue
        if has_dash(text):
            errors.append("%s contains an em dash or a dash break" % name)
        if name.startswith("exports/project-"):
            continue                              # stays inside its project, where its own names and addresses belong
        for label, pattern in PRIVATE_PATTERNS:
            hit = pattern.search(text)
            if hit:
                errors.append("%s contains what looks like a private %s: %s" % (name, label, hit.group(0)))
        for q in quotes:
            if q in text:
                errors.append("%s contains an evidence quote: %s" % (name, q[:60]))
    return errors


def load_all(root=ROOT):
    """Returns (rules, profiles, errors): everything read from the folder, with what could not be read."""
    rules, errors = load_rules(root)
    profiles, perrors = load_profiles(root)
    return rules, profiles, errors + perrors


def compile_map(rules, profiles, root=ROOT):
    """Validates and builds in memory. Returns (errors, outputs); outputs is empty when there are errors."""
    errors = validate(rules, profiles, root)
    if errors:
        return errors, {}
    try:
        outputs = build_outputs(rules, profiles)
        errors = check_outputs(outputs, rules)
    except BuildError as e:
        return [str(e)], {}
    return errors, ({} if errors else outputs)


def write_outputs(outputs, root=ROOT):
    """Writes the generated files that changed."""
    for rel, text in outputs.items():
        full = full_path(root, rel)
        if not os.path.isfile(full) or read_text(full) != text:
            write_text(full, text)


def run(root=ROOT, write=True):
    """Returns (errors, outputs, rules). Writes the outputs only when there are no errors."""
    rules, profiles, errors = load_all(root)
    outputs = {}
    if not errors:
        errors, outputs = compile_map(rules, profiles, root)
    if write and not errors:
        write_outputs(outputs, root)
    return errors, outputs, rules


def installed_text(core_text, root=ROOT):
    """The core with the real folder in place of the placeholder."""
    folder = folder_text(root)
    text = core_text.replace(PLACEHOLDER_LINE, "Installed copy of the core in %s. Rebuild with `python build.py --install`." % folder)
    return text.replace("<BEHAVIOR_MAP_DIR>", folder)


def split_installed(text):
    """(text before our part, text after it), or None when the file holds no marked part."""
    if BLOCK_START not in text or BLOCK_END not in text.split(BLOCK_START, 1)[1]:
        return None
    before, rest = text.split(BLOCK_START, 1)
    after = rest.split(BLOCK_END, 1)[1]
    return before, after[1:] if after.startswith("\n") else after


def installed_from(root=ROOT, target=INSTALL_TARGET):
    """True when the installed file was built from this folder (not from another copy of the map)."""
    if not os.path.isfile(target):
        return False
    text = read_text(target)
    return GENERATED in text and ("in %s." % folder_text(root)) in text


def install(core_text, target=INSTALL_TARGET, root=ROOT):
    """Puts the core into a tool's global instructions file, as a marked part of it.

    Text the person wrote there themselves is kept: the core goes below it, and the file as it was is saved
    once beside it. Later installs rewrite the marked part only."""
    block = BLOCK_START + "\n" + installed_text(core_text, root) + BLOCK_END + "\n"
    old = read_text(target) if os.path.isfile(target) else ""
    parts, note = split_installed(old), ""
    if parts:
        text = parts[0] + block + parts[1]
    elif not old.strip() or GENERATED in old:        # no file yet, or one from before the marks: all of it is ours
        text = block
    else:
        backup = target + BACKUP_SUFFIX
        if not os.path.isfile(backup):
            write_text(backup, old)
        text = old.rstrip("\n") + "\n\n" + block
        note = " (your own text is kept above the rules; the file as it was is saved as %s)" % os.path.basename(backup)
    if text != old:
        write_text(target, text)
    return "installed: %s%s" % (folder_text(target), note)


def uninstall(target=INSTALL_TARGET):
    """Takes the core out again and leaves the person's own text. The file goes when nothing else is in it."""
    if not os.path.isfile(target):
        return "nothing installed: %s" % folder_text(target)
    old = read_text(target)
    parts = split_installed(old)
    if not parts and GENERATED not in old:
        return "nothing installed: %s holds no rules from build.py" % folder_text(target)
    rest = (parts[0].rstrip("\n") + "\n" + parts[1]).strip("\n") if parts else ""
    if rest.strip():
        write_text(target, rest + "\n")
        return "removed the rules from %s, your own text is still there" % folder_text(target)
    os.remove(target)
    return "removed: %s" % folder_text(target)


def refresh_installed(outputs, root=ROOT, also=(), targets=None):
    """Installs for the tools named in `also` and keeps every copy that was built from this folder current."""
    notes = []
    for tool, (_label, rel, target) in (targets or INSTALL_TARGETS).items():
        if tool in also or installed_from(root, target):
            notes.append(install(outputs[rel], target, root))
    return notes


def tools_named(argv, flag):
    """The tools after --install or --uninstall: a tool name, `all`, or nothing (Claude Code)."""
    if flag not in argv:
        return []
    word = argv[argv.index(flag) + 1] if argv.index(flag) + 1 < len(argv) else "claude"
    if word == "all":
        return list(INSTALL_TARGETS)
    if word.startswith("--"):
        return ["claude"]
    if word not in INSTALL_TARGETS:
        raise BuildError("unknown tool %s: use %s or all" % (word, ", ".join(INSTALL_TARGETS)))
    return [word]


def has_map(root=ROOT):
    return os.path.isdir(os.path.join(root, "rules"))


def init(root=ROOT):
    """Starts a map from the starter rules. Never touches a folder that already holds rules."""
    if has_map(root):
        return "there is already a map in %s" % folder_text(root)
    today = datetime.date.today().isoformat()
    for name in ("rules", "profiles"):
        shutil.copytree(os.path.join(CODE, "starter", name), os.path.join(root, name))
    shutil.copy(os.path.join(CODE, "starter", "conflicts.md"), root)
    for folder, _dirs, files in os.walk(os.path.join(root, "rules")):
        for name in files:                       # the starter rules count as said today, so none shows as stale
            path = os.path.join(folder, name)
            write_text(path, read_text(path).replace("last_seen: null", "last_seen: " + today))
    write_text(os.path.join(root, ".gitignore"), "signals/state.json\nsignals/skills.json\nsignals/judge.json\n_work/*.log\n_work/*.lock\n")
    run(root)
    return "started your map in %s with the starter rules" % folder_text(root)


def settings(root=ROOT):
    """The map's optional settings.json: {"project_folders": [...], "own_skills": "..."}. Empty when there is none."""
    path = os.path.join(root, "settings.json")
    try:
        data = json.loads(read_text(path)) if os.path.isfile(path) else {}
    except ValueError:
        data = {}
    return data if isinstance(data, dict) else {}


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except AttributeError:
        pass
    if argv[:1] == ["init"]:
        print(init())
        return 0
    if not has_map():
        print("No map yet in %s. Start one with: python build.py init" % folder_text(ROOT))
        return 1
    try:
        wanted, unwanted = tools_named(argv, "--install"), tools_named(argv, "--uninstall")
    except BuildError as e:
        print(e)
        return 1
    if unwanted:
        for tool in unwanted:
            print(uninstall(INSTALL_TARGETS[tool][2]))
        return 0
    check_only = "--check" in argv
    errors, outputs, rules = run(ROOT, write=not check_only)
    if errors:
        print("%d problem(s):" % len(errors))
        for e in errors:
            print("  - " + e)
        return 1
    on = sum(r["enabled"] is True for r in rules)
    if check_only:
        stale = [rel for rel, text in outputs.items()
                 if not os.path.isfile(full_path(ROOT, rel)) or read_text(full_path(ROOT, rel)) != text]
        print("OK: %d rules (%d on), all checks pass." % (len(rules), on))
        if stale:
            print("Note: these generated files are out of date, run `python build.py`: " + ", ".join(stale))
    else:
        print("OK: %d rules (%d on). Wrote %d files: %s" % (len(rules), on, len(outputs), ", ".join(sorted(outputs))))
        # --install puts the core in place; afterwards every build keeps the installed copies current
        for note in refresh_installed(outputs, ROOT, wanted):
            print(note)
    return 0


if __name__ == "__main__":
    sys.exit(main())
